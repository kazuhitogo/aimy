#[test]
fn test_ref_mid() {
    assert_eq!(mid(1, 2), 1);
    assert_eq!(mid(-1, -2), -1);
    assert_eq!(mid(-3, 0), -1);
    assert_eq!(mid(7, -2), 2);
    assert_eq!(mid(9223372036854775807, 9223372036854775807), 9223372036854775807);
    assert_eq!(mid(-9223372036854775808, -9223372036854775808), -9223372036854775808);
    assert_eq!(mid(9223372036854775807, -9223372036854775808), 0);
    assert_eq!(mid(-9223372036854775808, -9223372036854775807), -9223372036854775807);
    assert_eq!(mid(9223372036854775807, 9223372036854775806), 9223372036854775806);
}
