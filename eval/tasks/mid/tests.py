    assert mid(-1, -2) == -1
    assert mid(-3, 0) == -1
    assert mid(7, -2) == 2
    assert mid(9223372036854775807, 9223372036854775807) == 9223372036854775807
    assert mid(-9223372036854775808, -9223372036854775808) == -9223372036854775808
    assert mid(9223372036854775807, -9223372036854775808) == 0
    assert mid(-9223372036854775808, -9223372036854775807) == -9223372036854775807
    assert mid(9223372036854775807, 9223372036854775806) == 9223372036854775806
