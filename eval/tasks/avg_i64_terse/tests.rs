#[test]
fn test_ref_avg_i64() {
    assert_eq!(avg_i64(&[]), Err("empty".to_string()));
    assert_eq!(avg_i64(&[1, 2]), Ok(1));
    assert_eq!(avg_i64(&[-1, -2]), Ok(-1));
    assert_eq!(avg_i64(&[7, -2]), Ok(2));
    assert_eq!(avg_i64(&[-7, 2]), Ok(-2));
    assert_eq!(avg_i64(&[9223372036854775807, 9223372036854775807, 9223372036854775807]), Ok(9223372036854775807));
    assert_eq!(avg_i64(&[-9223372036854775808, -9223372036854775808]), Ok(-9223372036854775808));
    assert_eq!(avg_i64(&[9223372036854775807, -9223372036854775808]), Ok(0));
    assert_eq!(avg_i64(&[9223372036854775807, 9223372036854775807, -9223372036854775807]), Ok(3074457345618258602));
    assert_eq!(avg_i64(&[-9223372036854775808, -9223372036854775808, 1]), Ok(-6148914691236517205));
}
