#[test]
fn test_ref_mul_mod() {
    assert_eq!(mul_mod(3, 4, 5), 2);
    assert_eq!(mul_mod(0, 5, 7), 0);
    assert_eq!(mul_mod(0, 0, 1), 0);
    assert_eq!(mul_mod(999999999999999999, 999999999999999999, 1000000000000000000), 1);
    assert_eq!(mul_mod(100000000000000003, 100000000000000007, 999999999999999989), 110000000000000032);
    assert_eq!(mul_mod(999999999999999989, 999999999999999967, 999999999999999993), 104);
    assert_eq!(mul_mod(123456789012345678, 987654321098765432, 1000000000000000000), 322511812221002896);
}
