def test_ref_hist():
    assert hist([0, 1, 2, 3, 9, 10, -1], 0, 10, 5) == [2, 2, 0, 0, 1]
    assert hist([-10, -6, -5, -1, 0, 5], -10, 0, 2) == [2, 2]
    assert hist([], 0, 4, 2) == [0, 0]
    assert hist([-1, -2, -3, 3], 0, 3, 3) == [0, 0, 0]
    assert hist([-7, -4, -3, 2], -6, 3, 3) == [1, 1, 1]
